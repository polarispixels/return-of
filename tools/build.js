#!/usr/bin/env node
// Builds the chapter pages and the contents list. Run: node tools/build.js
//
// Input:  content/chapters.json          the book's parts and chapters, in order
//         content/chapters/NN-slug.html  one HTML fragment per chapter (body only)
// Output: chapters/NN-slug.html          a full page per chapter
//         index.html                     the contents list, between the contents markers
//
// The output is committed, so the site still opens straight from the files.
// tools/check.js fails if the output is stale. No dependencies.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const FONTS = 'https://fonts.googleapis.com/css2?family=Inter:wght@400;700&family=Playfair+Display:ital,wght@0,700;0,900;1,400&family=Source+Serif+4:opsz,wght@8..60,400;8..60,600&display=swap';
const START = '<!-- contents:start (generated by tools/build.js, do not edit) -->';
const END = '<!-- contents:end -->';

// The flat, numbered chapter list.
function chapters() {
  const book = JSON.parse(read('content/chapters.json'));
  const list = [];
  for (const part of book.parts) {
    for (const ch of part.chapters) {
      const number = list.length + 1;
      const file = String(number).padStart(2, '0') + '-' + ch.slug + '.html';
      list.push({ ...ch, number, file, part: 'Part ' + part.numeral + ': ' + part.title });
    }
  }
  return { book, list };
}

// Number the tables in a chapter: "Table" becomes "Table 4.1", "Table 4.2", ...
function numberTables(html, chapterNumber) {
  let n = 0;
  return html.replace(/(<span class="figure-number">)\s*Table\s*(<\/span>)/g, (m, open, close) => {
    n += 1;
    return open + 'Table ' + chapterNumber + '.' + n + close;
  });
}

function chapterPage(ch, prev, next) {
  const source = 'content/chapters/' + ch.file;
  const body = fs.existsSync(path.join(root, source))
    ? numberTables(read(source).trim(), ch.number)
    : '<p class="lead">This chapter has not been written yet.</p>';
  const link = (c, rel, word) => c
    ? '<a class="chapter-nav-' + rel + '" href="' + c.file + '" rel="' + rel + '"><span class="label">' + word +
      '</span><span class="chapter-nav-title">' + c.number + '. ' + esc(c.title) + '</span></a>'
    : '<span></span>';
  const charts = body.includes('data-chart=') ? '\n  <script src="../js/chart.js"></script>' : '';

  return `<!doctype html>
<!-- Generated by tools/build.js from ${source}. Edit that file, not this one. -->
<html lang="en" data-style="editorial">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${ch.number}. ${esc(ch.title)}: Return Of</title>
  <meta name="description" content="${esc(ch.summary)}">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="${FONTS}" rel="stylesheet">
  <link rel="stylesheet" href="../css/themes.css">
  <link rel="stylesheet" href="../css/site.css">
</head>
<body>
  <div class="wrap">
    <header class="masthead label">
      <a href="../index.html">Return Of</a>
      <span>${esc(ch.part)}</span>
    </header>

    <main>
      <article class="chapter">
        <header class="chapter-head">
          <p class="chapter-kicker label">Chapter ${ch.number} <span class="badge">Preliminary draft</span></p>
          <h1 class="chapter-title">${esc(ch.title)}</h1>
          <p class="standfirst">${esc(ch.summary)}</p>
        </header>

        <div class="prose chapter-body">
${body}
        </div>
      </article>

      <nav class="chapter-nav" aria-label="Chapters">
        ${link(prev, 'prev', 'Previous')}
        ${link(next, 'next', 'Next')}
      </nav>
    </main>

    <footer class="colophon label">
      <nav>
        <a href="../index.html#contents">Contents</a>
        <a href="../docs/index.html">Docs</a>
        <a href="https://github.com/polarispixels/return-of">GitHub</a>
      </nav>
      <span>Study notes, not financial advice. <span data-version></span></span>
    </footer>
  </div>

  <script src="../js/version.js"></script>${charts}
</body>
</html>
`;
}

function contentsList(book, list) {
  let i = 0;
  const parts = book.parts.map((part) => {
    const items = part.chapters.map(() => {
      const ch = list[i++];
      return `            <li><a href="chapters/${ch.file}"><span class="contents-number">${ch.number}</span><span class="contents-text"><span class="contents-name">${esc(ch.title)}</span><span class="contents-summary">${esc(ch.summary)}</span></span></a></li>`;
    }).join('\n');
    return `        <div class="contents-part">
          <h3 class="label">Part ${part.numeral}: ${esc(part.title)}</h3>
          <ol>
${items}
          </ol>
        </div>`;
  }).join('\n');
  return `${START}
      <section class="contents" id="contents" aria-labelledby="contents-title">
        <h2 class="contents-title" id="contents-title">Contents</h2>
${parts}
      </section>
      ${END}`;
}

// Returns { path: content } for every generated file.
function build() {
  const { book, list } = chapters();
  const out = {};
  list.forEach((ch, idx) => { out['chapters/' + ch.file] = chapterPage(ch, list[idx - 1], list[idx + 1]); });

  const home = read('index.html');
  const a = home.indexOf(START), b = home.indexOf(END);
  if (a < 0 || b < 0) throw new Error('index.html: contents markers not found');
  out['index.html'] = home.slice(0, a) + contentsList(book, list) + home.slice(b + END.length);
  return { out, list };
}

module.exports = { build, chapters };

if (require.main === module) {
  const { out } = build();
  fs.mkdirSync(path.join(root, 'chapters'), { recursive: true });
  for (const [file, content] of Object.entries(out)) fs.writeFileSync(path.join(root, file), content);
  console.log('Built ' + Object.keys(out).length + ' files');
}
